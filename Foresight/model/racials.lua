-- Foresight racials: access to the generated per-race racial data (race_racials.lua).
-- IMPORTANT: live snapshot stats (UnitStat/UnitHealthMax/GetDodgeChance...) ALREADY
-- include racial passives, so the model never folds them into the base build - that
-- would double-count. Racials surface as what-if deltas (Loadout:withRacial/withRace),
-- synergy contributors, and panel/tooltip lines.

local _, HM = ...
if not HM then HM = _G.Foresight or {}; _G.Foresight = HM end

local Racials = {}
HM.Racials = Racials

-- classToken ("MAGE") -> classId, derived from generated classNames (id -> "Mage").
local tokenToClassId
local function classIdFor(classToken)
    if not tokenToClassId then
        tokenToClassId = {}
        for id, name in pairs((HM.gen and HM.gen.classNames) or {}) do
            tokenToClassId[name:upper()] = id
        end
    end
    return classToken and tokenToClassId[classToken] or nil
end

-- SkillLineAbility ClassMask gate: bit 1<<(classId-1). 0 = all classes.
function Racials.classMatches(classMask, classToken)
    if not classMask or classMask == 0 then return true end
    local id = classIdFor(classToken)
    if not id then return false end
    return math.floor(classMask / 2 ^ (id - 1)) % 2 == 1
end

-- UnitRace #2 token -> raceId fallback ("Scourge" = Undead = 5; both Skyborne
-- variants share one token - the map resolves to the lower id, 95).
function Racials.raceIdForToken(token)
    return token and HM.gen and HM.gen.raceTokens and HM.gen.raceTokens[token] or nil
end

function Racials.raceEntry(raceId)
    return raceId and HM.gen and HM.gen.racials and HM.gen.racials[raceId] or nil
end

-- Racials of a race that apply to the given class; passiveOnly drops actives
-- (actives are tooltip/advice surface, never modifier folds).
function Racials.forRace(raceId, classToken, passiveOnly)
    local race = Racials.raceEntry(raceId)
    local list = {}
    for _, sp in ipairs((race and race.spells) or {}) do
        if (not passiveOnly or sp.passive) and Racials.classMatches(sp.classMask, classToken) then
            list[#list + 1] = sp
        end
    end
    return list
end

-- Resolve one racial spell entry (+ its raceId) from the generated bySpell index.
function Racials.bySpell(spellID)
    local gen = HM.gen
    local raceId = gen and gen.racialsBySpell and gen.racialsBySpell[spellID]
    local race = raceId and gen.racials[raceId]
    for _, sp in ipairs((race and race.spells) or {}) do
        if sp.spellID == spellID then return sp, raceId end
    end
    return nil
end

return Racials
