"""Generate the three crowd-share allow-list mirrors from the ONE source of truth.

Usage:
    python gen_crowd_schema.py          # write all three mirrors
    python gen_crowd_schema.py --check  # fail (exit 1) if any mirror has drifted

Source:  data/crowd-schema.json  (the allow-list: keys, types, clamps, caps, tier)
Mirrors:
  - Foresight/data/generated/crowd_schema.lua   (addon: allow-list + forbidden + caps)
  - web/crowd-schema.js                          (web sanitize: full field schema)
  - web/firestore.rules  validContribution block (server gate, between markers)

WHY: the allow-list used to live hand-copied in three places (crowd.lua, app.js,
firestore.rules). A field added to one and forgotten in another is a PII-leak waiting
to happen. Now there is one source; the ship gate (run_tests.py --> check()) refuses to
pass if the committed mirrors don't match a fresh generation. Adding a field = edit the
JSON + regenerate; removing one reverts cleanly.

This generator is offline build tooling - it never ships and never networks.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).parent.parent
SCHEMA_PATH = ROOT / "data" / "crowd-schema.json"
LUA_PATH = ROOT / "Foresight" / "data" / "generated" / "crowd_schema.lua"
JS_PATH = ROOT / "web" / "crowd-schema.js"
RULES_PATH = ROOT / "web" / "firestore.rules"

RULES_BEGIN = "// BEGIN generated validContribution"
RULES_END = "// END generated validContribution"

GEN_NOTE = "GENERATED by pipeline/gen_crowd_schema.py from data/crowd-schema.json - DO NOT EDIT."


# ---- load -------------------------------------------------------------------

def load_schema() -> dict:
    schema = json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))
    fields = schema["fields"]
    keys = [f["key"] for f in fields]
    if len(keys) != len(set(keys)):
        raise ValueError("crowd-schema.json: duplicate field key")
    for f in fields:
        if f["tier"] not in ("anon", "identifying"):
            raise ValueError(f"crowd-schema.json: field {f['key']} has unknown tier {f['tier']!r}")
        if f["kind"] not in ("const", "string", "number", "map"):
            raise ValueError(f"crowd-schema.json: field {f['key']} has unknown kind {f['kind']!r}")
    return schema


def allow_keys(schema: dict) -> list[str]:
    return [f["key"] for f in schema["fields"]]


def anon_keys(schema: dict) -> list[str]:
    return [f["key"] for f in schema["fields"] if f["tier"] == "anon"]


def caps(schema: dict) -> dict:
    return {f["key"]: f["maxSize"] for f in schema["fields"] if "maxSize" in f}


# ---- Lua mirror (addon) -----------------------------------------------------

def _lua_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _lua_list(items: list[str]) -> str:
    return "{ " + ", ".join(_lua_str(x) for x in items) + " }"


def emit_lua(schema: dict) -> str:
    cap_items = caps(schema)
    cap_parts = ", ".join(f"{k} = {v}" for k, v in sorted(cap_items.items()))
    lines = [
        f"-- {GEN_NOTE}",
        "-- The crowd-share allow-list, single-sourced. core/crowd.lua reads these so the",
        "-- payload builder's key set, forbidden list and caps can never drift from the",
        "-- web sanitize + Firestore rules (which are generated from the same JSON).",
        "local _, HM = ...",
        "if not HM then HM = _G.Foresight or {}; _G.Foresight = HM end",
        "HM.gen = HM.gen or {}",
        "HM.gen.crowdSchema = {",
        f"    version = {int(schema['schemaVersion'])},",
        f"    allow = {_lua_list(allow_keys(schema))},",
        f"    anonAllow = {_lua_list(anon_keys(schema))},",
        f"    forbidden = {_lua_list(schema['forbidden'])},",
        f"    caps = {{ {cap_parts} }},",
        "}",
    ]
    return "\n".join(lines) + "\n"


# ---- JS mirror (web sanitize) -----------------------------------------------

def _js(v) -> str:
    return json.dumps(v)


def emit_js(schema: dict) -> str:
    field_lines = []
    for f in schema["fields"]:
        parts = [f'key: {_js(f["key"])}', f'tier: {_js(f["tier"])}', f'kind: {_js(f["kind"])}']
        for opt in ("value", "min", "max", "maxSize", "matches"):
            if opt in f:
                parts.append(f"{opt}: {_js(f[opt])}")
        parts.append(f'required: {_js(f["required"])}')
        field_lines.append("    { " + ", ".join(parts) + " },")
    lines = [
        f"// {GEN_NOTE}",
        "// web/app.js imports this so its allow-list + banned keys match the addon and the",
        "// Firestore rules exactly. Edit data/crowd-schema.json and regenerate; never here.",
        "export const CROWD_SCHEMA = {",
        f"  version: {int(schema['schemaVersion'])},",
        "  fields: [",
        *field_lines,
        "  ],",
        f"  allow: {_js(allow_keys(schema))},",
        f"  forbidden: {_js(schema['forbidden'])},",
        f"  caps: {_js(caps(schema))},",
        "};",
    ]
    return "\n".join(lines) + "\n"


# ---- Firestore rules mirror (server gate) -----------------------------------

def _rule_clause(f: dict) -> str:
    """The validation clause for one field (without the optional-guard wrapper)."""
    k = f["key"]
    kind = f["kind"]
    if kind == "const":
        return f"d.{k} == {_js(f['value'])}"
    if kind == "string":
        c = [f"d.{k} is string", f"d.{k}.size() <= {int(f['maxSize'])}"]
        if "matches" in f:
            c.append(f"d.{k}.matches('{f['matches']}')")
        return " && ".join(c)
    if kind == "number":
        c = [f"d.{k} is number"]
        if "min" in f:
            c.append(f"d.{k} >= {_js(f['min'])}")
        if "max" in f:
            c.append(f"d.{k} <= {_js(f['max'])}")
        return " && ".join(c)
    if kind == "map":
        c = [f"d.{k} is map"]
        if "maxSize" in f:
            c.append(f"d.{k}.size() <= {int(f['maxSize'])}")
        return " && ".join(c)
    raise ValueError(f"unknown kind {kind}")


def emit_rules_block(schema: dict) -> str:
    """The validContribution function, byte-for-byte deterministic, 4-space base indent."""
    keys = allow_keys(schema)
    hasonly = "', '".join(keys)
    clauses = [f"d.keys().hasOnly(['{hasonly}'])"]
    for f in schema["fields"]:
        clause = _rule_clause(f)
        # 'const' and 'required' fields are asserted unconditionally; optional fields are
        # only checked when present. (All of today's fields are anon; the identifying tier
        # will add a `named`-gated guard here when it lands - Story C.)
        if f["kind"] == "const" or f.get("required"):
            clauses.append(clause)
        else:
            clauses.append(f"(!('{f['key']}' in d) || ({clause}))")
    body = "\n          && ".join(clauses)
    return (
        "    function validContribution(d) {\n"
        f"      return {body};\n"
        "    }"
    )


def render_rules_file(schema: dict, current: str) -> str:
    if RULES_BEGIN not in current or RULES_END not in current:
        raise ValueError(
            f"{RULES_PATH} is missing the generator markers "
            f"({RULES_BEGIN!r} / {RULES_END!r})")
    pre, rest = current.split(RULES_BEGIN, 1)
    _, post = rest.split(RULES_END, 1)
    block = emit_rules_block(schema)
    return f"{pre}{RULES_BEGIN}\n{block}\n    {RULES_END}{post}"


# ---- drive ------------------------------------------------------------------

def _targets(schema: dict) -> dict[Path, str]:
    return {
        LUA_PATH: emit_lua(schema),
        JS_PATH: emit_js(schema),
        RULES_PATH: render_rules_file(schema, RULES_PATH.read_text(encoding="utf-8")),
    }


def generate() -> list[Path]:
    schema = load_schema()
    written = []
    for path, content in _targets(schema).items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        written.append(path)
    return written


def check() -> bool:
    """True iff every committed mirror equals a fresh generation (gate's drift guard)."""
    schema = load_schema()
    drifted = []
    for path, content in _targets(schema).items():
        existing = path.read_text(encoding="utf-8") if path.exists() else None
        if existing != content:
            drifted.append(path.relative_to(ROOT).as_posix())
    if drifted:
        print("CROWD SCHEMA DRIFT RED - these mirrors differ from data/crowd-schema.json;")
        print("run `python pipeline/gen_crowd_schema.py` and commit the result:")
        for d in drifted:
            print(f"  {d}")
        return False
    print("crowd schema parity green: addon + web sanitize + firestore.rules all match "
          "data/crowd-schema.json")
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="verify committed mirrors match the source; exit 1 on drift")
    args = parser.parse_args()
    if args.check:
        return 0 if check() else 1
    written = generate()
    for path in written:
        print(f"wrote {path.relative_to(ROOT).as_posix()} ({path.stat().st_size:,} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
