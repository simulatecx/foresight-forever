#!/usr/bin/env python3
"""Bake the Firebase `verifiedRules` collection into Foresight/data/generated/verified_rules.lua.

Offline maintainer step (like fetch_baselines.py). The addon never networks; this pulls the
owner/crowd-verified per-talent rank rules (written by pipeline/push_verified.py) and writes
`HM.gen.verifiedRules = { [talentId] = "perRank"|"maxTotal", ... }` so a FRESH character gets
them without scanning. Ships empty until the owner pushes.

`verifiedRules` is world-readable by the rules, but App Check rejects anonymous REST reads -
so authenticate with the maintainer's gcloud OAuth token (same as fetch_baselines.py). No
service-account key in the repo.

Usage:
    gcloud auth login            # if the token has expired
    python pipeline/fetch_verified.py [--project wow-foresight]
"""
from __future__ import annotations

import argparse
import json
import urllib.request
from pathlib import Path

from fetch_baselines import access_token, decode, lua

DEFAULT_PROJECT = "wow-foresight"
OUT = Path(__file__).resolve().parent.parent / "Foresight" / "data" / "generated" / "verified_rules.lua"
REST = ("https://firestore.googleapis.com/v1/projects/{project}"
        "/databases/(default)/documents/verifiedRules?pageSize=1000")

VALID_RULES = ("perRank", "maxTotal")


def fetch_rules(project: str, token: str) -> dict:
    url = REST.format(project=project)
    rules: dict[int, str] = {}
    while True:
        req = urllib.request.Request(url, headers={"Authorization": "Bearer " + token})
        with urllib.request.urlopen(req, timeout=60) as resp:
            data = json.loads(resp.read())
        if "error" in data:
            raise SystemExit("Firestore read failed: " + data["error"].get("message", "?"))
        for doc in data.get("documents", []):
            tid = doc["name"].split("/")[-1]
            fields = {k: decode(v) for k, v in doc.get("fields", {}).items()}
            rule = fields.get("rule")
            # Shape-guard: only well-formed, in-vocabulary rules bake (a malformed doc never
            # reaches the client as a silent bad rule).
            if rule in VALID_RULES and str(tid).lstrip("-").isdigit():
                rules[int(tid)] = rule
        nxt = data.get("nextPageToken")
        if not nxt:
            return rules
        url = REST.format(project=project) + "&pageToken=" + nxt


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--project", default=DEFAULT_PROJECT)
    args = ap.parse_args()

    rules = fetch_rules(args.project, access_token())
    body = (
        "-- GENERATED by pipeline/fetch_verified.py from the Firebase verifiedRules collection - DO NOT EDIT.\n"
        "-- The owner/crowd-verified per-talent rank rules (talentId -> \"perRank\" | \"maxTotal\"), baked\n"
        "-- so a FRESH character gets them without scanning a single tooltip. Ships EMPTY and fills as\n"
        "-- the owner pushes decided rules (pipeline/push_verified.py). Consumed by formulas.F.crowdRule\n"
        "-- as the \"crowd\" tier BENEATH the hand-curated overrides.rankRules; the player's own scan\n"
        "-- (selfVerifiedRule) and datamined op.values still outrank it. Empty/absent = today's behaviour.\n"
        "local _, HM = ...\n"
        "if not HM then HM = _G.Foresight or {}; _G.Foresight = HM end\n"
        "HM.gen = HM.gen or {}\n"
        "HM.gen.verifiedRules = " + lua(rules) + "\n"
    )
    OUT.write_text(body, encoding="utf-8")
    print("wrote %d verified rule(s) -> %s" % (len(rules), OUT))


if __name__ == "__main__":
    main()
